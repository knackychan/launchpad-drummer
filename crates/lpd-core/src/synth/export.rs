//! Parameter metadata shared with the UI (keys synth plan K1).
use super::{factory, params::*, patch::Category};
use crate::devices::lcxl::SYNTH_KNOBS;
use serde_json::{json, Value};

fn unit(u: Unit) -> &'static str {
    match u {
        Unit::Pct => "pct",
        Unit::Hz => "hz",
        Unit::Sec => "sec",
        Unit::Cents => "cents",
        Unit::Semis => "semis",
        Unit::Db => "db",
        Unit::Pan => "pan",
        Unit::Deg => "deg",
        Unit::EnvOct => "envOct",
        Unit::Drive24 => "drive24",
        Unit::Drive36 => "drive36",
        Unit::Oct => "oct",
        Unit::Voices => "voices",
    }
}

pub fn ui_meta() -> Value {
    let init = SynthParams::default();
    let params: Vec<Value> = ParamId::ALL
        .iter()
        .map(|&id| {
            let m = id.meta();
            let mut v =
                json!({"id":m.id,"section":m.section,"label":m.label,"default":id.get(&init)});
            match m.kind {
                Kind::Bool => v["kind"] = json!("bool"),
                Kind::Choice { ids, labels } => {
                    v["kind"] = json!("choice");
                    v["choices"] = json!(ids);
                    v["labels"] = json!(labels);
                }
                Kind::Int { min, max, unit: u } => {
                    v["kind"] = json!("int");
                    v["min"] = json!(min);
                    v["max"] = json!(max);
                    v["unit"] = json!(unit(u));
                }
                Kind::Float {
                    min,
                    max,
                    taper,
                    unit: u,
                } => {
                    v["kind"] = json!("float");
                    v["min"] = json!(min);
                    v["max"] = json!(max);
                    v["unit"] = json!(unit(u));
                    v["taper"] = json!(match taper {
                        Taper::Lin => "lin",
                        Taper::Log => "log",
                        Taper::Cubic => "cubic",
                    });
                }
            }
            if let Some(d) = Dest::ALL.iter().find(|d| d.param() == Some(id)) {
                v["dest"] = json!(Dest::IDS[*d as usize]);
            }
            v
        })
        .collect();
    let dests: Vec<Value> = Dest::ALL.iter().map(|d| json!({"id":Dest::IDS[*d as usize],"label":Dest::LABELS[*d as usize],"param":d.param().map(|id| id.meta().id)})).collect();
    let sources: Vec<Value> = Source::ALL.iter().map(|s| json!({"id":Source::IDS[*s as usize],"label":Source::LABELS[*s as usize],"color":s.color()})).collect();
    let categories: Vec<Value> = Category::ALL
        .iter()
        .map(|c| json!({"id":c.id(),"label":c.label(),"color":c.color()}))
        .collect();
    let lcxl: Vec<Vec<&str>> = SYNTH_KNOBS
        .iter()
        .map(|row| row.iter().map(|id| id.meta().id).collect())
        .collect();
    let factory: Vec<Value> = factory::FACTORY_IDS
        .iter()
        .map(|id| {
            let p = factory::factory(id).expect("known factory id");
            json!({"id":id,"name":p.name,"category":p.category,"params":p.params})
        })
        .collect();
    json!({"params":params,"dests":dests,"sources":sources,"categories":categories,"lcxl":lcxl,"init":init,"factory":factory})
}

pub fn ui_meta_ts() -> String {
    format!("// Generated by `cargo test -p lpd-core --test synth_meta` from crates/lpd-core/src/synth. Do not edit.\nimport type {{ SynthMeta }} from './synth-types.ts';\n\nexport const SYNTH_META: SynthMeta = {};\n", serde_json::to_string_pretty(&ui_meta()).expect("metadata always serializes"))
}
